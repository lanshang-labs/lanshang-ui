import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {build} from 'esbuild';
const root=fileURLToPath(new URL('../',import.meta.url));
const inspect=entry=>build({entryPoints:[fileURLToPath(import.meta.resolve(entry))],absWorkingDir:root,bundle:true,write:false,metafile:true,format:'esm',platform:'browser',packages:'external',logLevel:'silent'});
const base=await inspect('@lanshang-labs/ui');
assert(!Object.keys(base.metafile.inputs).some(path=>/DockNavigation\.js$/.test(path)));
assert(!Object.values(base.metafile.outputs).flatMap(out=>out.imports).some(item=>/^motion(?:\/|$)/.test(item.path)));
const dock=await inspect('@lanshang-labs/ui/dock');
assert(Object.keys(dock.metafile.inputs).some(path=>path.endsWith('/DockNavigation.js')));
assert(!Object.keys(dock.metafile.inputs).some(path=>/\/(Provider|theme|index|charts)\.js$/.test(path)));
assert(Object.values(dock.metafile.outputs).flatMap(out=>out.imports).some(item=>item.path==='motion/react'));
const css=await build({entryPoints:['@lanshang-labs/ui/dock.css'],absWorkingDir:root,bundle:true,write:false,metafile:true,logLevel:'silent'});
assert.deepEqual(Object.keys(css.metafile.inputs).map(path=>path.split('/').pop()),['dock.css']);
const pkg=JSON.parse(readFileSync('package.json','utf8'));
assert.equal(pkg.peerDependencies.motion,'^14.6.0');assert.equal(pkg.peerDependenciesMeta.motion.optional,true);assert.equal(pkg.dependencies.motion,undefined);
assert(readFileSync('dist/licenses/motion-primitives/LICENSE','utf8').includes('Copyright (c) 2024 ibelick'));
console.log('Dock public entry, optional Motion boundary, standalone CSS and MIT license verified.');
