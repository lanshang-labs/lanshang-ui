// Integration check against an already-running local registry. Installs only in a fresh temp directory.
import {mkdtempSync,cpSync,readFileSync,writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {resolve,join} from 'node:path';
import {fileURLToPath} from 'node:url';
import {execFileSync} from 'node:child_process';
import assert from 'node:assert/strict';
const root=fileURLToPath(new URL('../',import.meta.url));
const base=new URL(process.env.LANSHANG_REGISTRY_BASE||'http://127.0.0.1:5177/');
if(!base.pathname.endsWith('/'))base.pathname+='/';
const cwd=mkdtempSync(join(tmpdir(),'lanshang-registry-consumer-'));
cpSync(resolve(root,'examples/registry-consumer'),cwd,{recursive:true});
const run=(bin,args)=>execFileSync(bin,args,{cwd,encoding:'utf8',timeout:180000,stdio:['pipe','pipe','pipe']});
const cli=resolve(root,'node_modules/.bin/shadcn');
const item=new URL('r/lanshang-blocks.json',base).href;
console.log(`Consumer: ${cwd}`);
console.log(run('npm',['install','--no-audit','--no-fund']));
console.log(run(cli,['add',item,'--yes']));
const files=['provider.tsx','blocks.tsx'].map(name=>join(cwd,'src/components/lanshang',name));
const before=files.map(path=>readFileSync(path,'utf8'));
assert(before[0].includes('@lanshang-labs/ui/styles.css'));
assert(before[1].includes('ProjectListBlock'));
console.log(run('npm',['run','build']));
console.log(run(cli,['add',item,'--yes']));
assert.deepEqual(files.map(path=>readFileSync(path,'utf8')),before,'Repeated install must preserve files');
const customized=before[1]+'\n// Consumer customization must survive dry-run.\n';
writeFileSync(files[1],customized);
console.log(run(cli,['add',item,'--dry-run']));
assert.equal(readFileSync(files[1],'utf8'),customized,'Dry-run must preserve customization');
console.log('PASS: fresh install, standalone build, repeat install, dry-run preservation.');
console.log('Temp consumer retained for inspection; overwrite prompt is verified separately.');
